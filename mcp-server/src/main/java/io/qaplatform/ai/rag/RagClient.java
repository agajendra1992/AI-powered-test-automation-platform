package io.qaplatform.ai.rag;

import io.qaplatform.mcp.tools.ToolException;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.Locale;
import java.util.Map;

/**
 * Client for the RAG service (rag/, FastAPI). Configured with {@code QA_RAG_URL} and the bearer key
 * in {@code QA_RAG_KEY} (environment only). Optional: without a URL every caller gets "not configured"
 * and falls back to its non-RAG behaviour.
 */
public final class RagClient {

    private static final JsonMapper JSON = JsonMapper.builder().build();
    private final String baseUrl;
    private final String key;
    // HTTP/1.1: the default HTTP/2 client sends an h2c upgrade on plain http, which uvicorn rejects for POSTs.
    private final HttpClient http = HttpClient.newBuilder().version(HttpClient.Version.HTTP_1_1).connectTimeout(Duration.ofSeconds(5)).build();

    public RagClient(String baseUrl, String key) {
        this.baseUrl = baseUrl == null || baseUrl.isBlank() ? null : baseUrl.replaceAll("/+$", "");
        this.key = key;
    }

    /** Key from QA_RAG_KEY, or from the file named by QA_RAG_KEY_FILE (Docker/Compose secrets). */
    public static RagClient fromEnvironment() {
        String key = System.getenv("QA_RAG_KEY");
        String keyFile = System.getenv("QA_RAG_KEY_FILE");
        if ((key == null || key.isBlank()) && keyFile != null && !keyFile.isBlank()) {
            try {
                key = java.nio.file.Files.readString(java.nio.file.Path.of(keyFile)).strip();
            } catch (IOException e) {
                throw new IllegalStateException("Cannot read QA_RAG_KEY_FILE " + keyFile, e);
            }
        }
        return new RagClient(setting("qa.rag.url"), key);
    }

    private static String setting(String key) {
        String sys = System.getProperty(key);
        return sys != null && !sys.isBlank() ? sys : System.getenv(key.toUpperCase(Locale.ROOT).replace('.', '_'));
    }

    public boolean configured() {
        return baseUrl != null;
    }

    public JsonNode search(String query, int k, Map<String, Object> filters, String mode) {
        return post("/rag/search", Map.of("query", query, "k", k, "filters", filters, "mode", mode), Duration.ofSeconds(60));
    }

    /** Retrieval + context construction only; answers are generated by the MCP server's own AI layer. */
    public JsonNode context(String query, int k, Map<String, Object> filters) {
        return post("/rag/query", Map.of("query", query, "k", k, "filters", filters, "answer", false), Duration.ofSeconds(60));
    }

    public JsonNode ingest(Map<String, Object> body) {
        return post("/rag/ingest", body, Duration.ofMinutes(10));
    }

    public JsonNode health() {
        requireConfigured();
        try {
            HttpResponse<String> r = http.send(HttpRequest.newBuilder(URI.create(baseUrl + "/rag/health")).timeout(Duration.ofSeconds(5)).GET().build(),
                    HttpResponse.BodyHandlers.ofString());
            return JSON.readTree(r.body());
        } catch (IOException e) {
            throw new ToolException("unavailable", "RAG service unreachable at " + baseUrl + ": " + e.getMessage());
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new ToolException("unavailable", "Interrupted");
        }
    }

    private JsonNode post(String path, Object body, Duration timeout) {
        requireConfigured();
        HttpRequest.Builder request = HttpRequest.newBuilder(URI.create(baseUrl + path)).timeout(timeout)
                .header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString(JSON.writeValueAsString(body)));
        if (key != null && !key.isBlank()) {
            request.header("Authorization", "Bearer " + key);
        }
        try {
            HttpResponse<String> r = http.send(request.build(), HttpResponse.BodyHandlers.ofString());
            if (r.statusCode() == 401 || r.statusCode() == 403) {
                throw ToolException.forbidden("RAG service refused the request (HTTP " + r.statusCode() + "): check QA_RAG_KEY and its role");
            }
            if (r.statusCode() / 100 != 2) {
                String detail = r.body().length() > 300 ? r.body().substring(0, 300) : r.body();
                throw new ToolException(r.statusCode() == 400 || r.statusCode() == 422 ? "invalid_argument" : "unavailable",
                        "RAG service error " + r.statusCode() + ": " + io.qaplatform.mcp.security.Redactor.redact(detail));
            }
            return JSON.readTree(r.body());
        } catch (IOException e) {
            throw new ToolException("unavailable", "RAG service unreachable at " + baseUrl + ": " + e.getMessage());
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new ToolException("unavailable", "Interrupted");
        }
    }

    private void requireConfigured() {
        if (!configured()) {
            throw new ToolException("unavailable", "Knowledge base not configured: start the RAG service (rag/) and set QA_RAG_URL and QA_RAG_KEY.");
        }
    }
}
